/* -------------------------------------------------------------------------- */
/*  Pattern data — computed once at module scope (pure + deterministic).       */
/* -------------------------------------------------------------------------- */

const EM_PENT: ScaleSelection = { root: 'E', type: 'minorPentatonic' };
const G_MAJOR: ScaleSelection = { root: 'G', type: 'major' };

const EM_PENT_PCS = getScalePitchClasses(EM_PENT);
const G_MAJOR_PCS = getScalePitchClasses(G_MAJOR);

const emLabel = scaleNoteLabels(EM_PENT);
const gLabel = scaleNoteLabels(G_MAJOR);

/**
 * The box data anchors on the tonic, so an open-string root (E) puts
 * position 1 up at fret 12 rather than at the nut. Same shape, but drawn
 * an octave high it breaks the "the five boxes chain up the neck" story.
 * Drop it back down when the whole box clears fret 12.
 */
function toLowestOctave(positions: RealizedPosition[]): RealizedPosition[] {
  if (positions.length === 0) return positions;
  const min = Math.min(...positions.map((p) => p.fret));
  return min >= 12
    ? positions.map((p) => ({ ...p, fret: p.fret - 12 }))
    : positions;
}

function toDots(
  positions: RealizedPosition[],
  root: PitchClass,
  label: (pc: PitchClass) => string,
): NeckDot[] {
  return positions.map((p) => {
    const pc = pitchClassFromMidi(STANDARD_TUNING_MIDI[p.string] + p.fret);
    return {
      string: p.string,
      fret: p.fret,
      label: label(pc),
      root: pc === root,
    };
  });
}

function fretRange(dots: NeckDot[]): string {
  const frets = dots.map((d) => d.fret);
  const lo = Math.min(...frets);
  const hi = Math.max(...frets);
  return lo === 0 ? `open position – fret ${hi}` : `frets ${lo}–${hi}`;
}

const PENTATONIC_POSITIONS: NeckPattern[] = ([1, 2, 3, 4, 5] as const)
  .map((n) => {
    const dots = toDots(
      toLowestOctave(
        realizeCagedShape(n, 'E', EM_PENT_PCS, 'minorPentatonic'),
      ),
      'E',
      emLabel,
    );
    return {
      id: `pent-${n}`,
      label: `Position ${n}`,
      sub: `E minor pentatonic · ${fretRange(dots)} · roots in blue`,
      dots,
      theory: 'scale:E:minorPentatonic',
      sortKey: Math.min(...dots.map((d) => d.fret)),
    };
  })
  // Present them in the order your hand actually meets them going up the neck.
  .sort((a, b) => a.sortKey - b.sortKey)
  .map(({ sortKey: _sortKey, ...pattern }) => pattern);

// Every pattern is anchored at or above pattern 1's fret so the seven of
// them chain UP the neck (3, 5, 7, 8, 10, 12, 14) the way they're always
// taught. Without the floor, pattern 7 would wrap back to fret 2 — the
// same shape, but it breaks the "they stack in order" story.
const THREE_NPS_MIN_FRET = 3;

const THREE_NPS_PATTERNS: NeckPattern[] = ([0, 1, 2, 3, 4, 5, 6] as const).map(
  (degree) => {
    const dots = toDots(
      threeNotesPerString(G_MAJOR_PCS, degree, { minFret: THREE_NPS_MIN_FRET }),
      'G',
      gLabel,
    );
    return {
      id: `3nps-${degree + 1}`,
      label: `Pattern ${degree + 1}`,
      sub: `G major · starts on ${gLabel(G_MAJOR_PCS[degree])} (degree ${
        degree + 1
      }) · ${fretRange(dots)}`,
      dots,
      theory: 'scale:G:major',
    };
  },
);

// The Super Duper three: two pentatonic boxes you already know plus the
