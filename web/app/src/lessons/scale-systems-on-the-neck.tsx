// and the underrated 3-pattern "Super Duper" approach.
//
// Every pattern is drawn INLINE. Sending the reader to /builder to see
// what "position 3" looks like breaks the lesson mid-thought, so the
// diagrams live on the page and the explorer link is a secondary "go hear
// it" action. Boxes come from the same verified guitarscale.org data
// /builder uses (realizeCagedShape); the 3NPS patterns are generated by
